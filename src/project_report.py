REPORT_PATH = ROOT_DIR / "outputs" / "project-report.html"
QUERY_HISTORY_PATH = ROOT_DIR / "outputs" / "query_history.jsonl"

NODE_LABELS = {
    "Article": "Wikipedia articles",
    "Topic": "Topics",
    "Chunk": "Text chunks",
}

RELATIONSHIP_LABELS = {
    "HAS_TOPIC": "Article-to-topic links",
    "HAS_CHUNK": "Article-to-text links",
    "MENTIONS_TOPIC": "Article-to-concept links",
}


def _load_query_history() -> list[dict[str, Any]]:
    """Load saved question-and-answer records."""
    if not QUERY_HISTORY_PATH.exists():
        return []

    records = []

    with QUERY_HISTORY_PATH.open("r", encoding="utf-8") as file:
        for line in file:
            try:
                record = json.loads(line)
            except json.JSONDecodeError:
                continue

            if isinstance(record, dict):
                records.append(record)

    return list(reversed(records))


def record_query(question: str, answer: str) -> Path:
    """Save a question and answer, then regenerate the HTML report."""
    # Append an immutable history record before rebuilding the report view.
    QUERY_HISTORY_PATH.parent.mkdir(parents=True, exist_ok=True)

    record = {
        "timestamp": datetime.now(timezone.utc).isoformat(
            timespec="seconds"
        ),
        "question": question,
        "answer": answer,
    }

    with QUERY_HISTORY_PATH.open("a", encoding="utf-8") as file:
        file.write(json.dumps(record, ensure_ascii=False) + "\n")

    return create_report()


def _get_ingestion_stats() -> dict[str, Any]:
    """Get current article, graph, and chunk statistics from Neo4j."""
    config = load_config()
    database = config["graph_store"].get("database", "neo4j")

    with get_graph_driver() as driver:
        article_records, _, _ = driver.execute_query(
            """
            MATCH (article:Article)-[:HAS_CHUNK]->(chunk:Chunk)
            RETURN article.title AS title,
                   count(chunk) AS chunk_count
            ORDER BY chunk_count DESC, title
            """,
            database_=database,
        )

        node_records, _, _ = driver.execute_query(
            """
            MATCH (node)
            UNWIND labels(node) AS label
            RETURN label, count(*) AS count
            ORDER BY label
            """,
            database_=database,
        )

        relationship_records, _, _ = driver.execute_query(
            """
            MATCH ()-[relationship]->()
            RETURN type(relationship) AS type,
                   count(*) AS count
            ORDER BY type
            """,
            database_=database,
        )

        chunk_length_records, _, _ = driver.execute_query(
            """
            MATCH (chunk:Chunk)
            WHERE chunk.text IS NOT NULL
            RETURN size(chunk.text) AS character_count
            """,
            database_=database,
        )

    return {
        "articles": [record.data() for record in article_records],
        "nodes": [record.data() for record in node_records],
        "relationships": [
            record.data() for record in relationship_records
        ],
        "chunk_lengths": [
            record["character_count"]
            for record in chunk_length_records
        ],
    }


def _make_bar_chart(
    title: str,
    labels: list[str],
    values: list[int],
    x_title: str,
    color: str,
) -> go.Figure:
    """Create a readable horizontal bar chart."""
    figure = go.Figure(
        go.Bar(
            x=values,
            y=labels,
            orientation="h",
            marker_color=color,
            text=values,
            textposition="outside",
            hovertemplate=(
                "<b>%{y}</b><br>"
                + x_title
                + ": %{x}<extra></extra>"
            ),
        )
    )

    figure.update_layout(
        title={"text": title, "x": 0.02, "xanchor": "left"},
        height=max(360, 100 + len(labels) * 48),
        margin={"l": 230, "r": 55, "t": 70, "b": 60},
        template="plotly_white",
        showlegend=False,
        font={"size": 14},
        xaxis_title=x_title,
        yaxis_title="",
    )
    figure.update_yaxes(autorange="reversed")
    figure.update_xaxes(rangemode="tozero")

    return figure


def _make_chunk_length_chart(
    chunk_lengths: list[int],
) -> go.Figure:
    """Show how many chunks fall into each character-length range."""
    figure = go.Figure(
        go.Histogram(
            x=chunk_lengths,
            nbinsx=20,
            marker_color="#00A884",
            hovertemplate=(
                "Chunk length range: %{x}<br>"
                "No. of chunks: %{y}<extra></extra>"
            ),
        )
    )

    figure.update_layout(
        title={
            "text": "How long are the stored text chunks?",
            "x": 0.02,
            "xanchor": "left",
        },
        height=400,
        margin={"l": 90, "r": 45, "t": 70, "b": 70},
        template="plotly_white",
        showlegend=False,
        font={"size": 14},
        xaxis_title="Characters in a chunk",
        yaxis_title="No. of chunks in this length range",
    )

    return figure


def _make_ingestion_tab(stats: dict[str, Any]) -> str:
    """Build the ingestion tab, including charts and explanations."""
    articles = stats["articles"]
    nodes = stats["nodes"]
    relationships = stats["relationships"]
    chunk_lengths = stats["chunk_lengths"]

    node_counts = {
        item["label"]: item["count"]
        for item in nodes
    }
    relationship_counts = {
        item["type"]: item["count"]
        for item in relationships
    }

    total_articles = node_counts.get("Article", 0)
    total_topics = node_counts.get("Topic", 0)
    total_chunks = node_counts.get("Chunk", 0)
    total_relationships = sum(relationship_counts.values())

    chart_sections = []

    if articles:
        article_chart = _make_bar_chart(
            title="How many text chunks came from each article?",
            labels=[item["title"] for item in articles],
            values=[item["chunk_count"] for item in articles],
            x_title="Text chunks",
            color="#5965E9",
        )

        chart_sections.append(
            """
            <section class="chart-card">
              <p class="explanation">
                Each bar represents one Wikipedia article. Its length
                shows how many text chunks were created from that article.
                A chunk is a section of text—not a character. Longer
                articles usually produce more chunks.
              </p>
              """
            + article_chart.to_html(
                full_html=False,
                include_plotlyjs="cdn",
                config={"responsive": True},
            )
            + "</section>"
        )

    readable_node_labels = [
        NODE_LABELS.get(label, label)
        for label in node_counts
    ]
    node_chart = _make_bar_chart(
        title="What information is stored?",
        labels=readable_node_labels,
        values=list(node_counts.values()),
        x_title="Stored items",
        color="#F05A3A",
    )

    chart_sections.append(
        """
        <section class="chart-card">
          <p class="explanation">
            These bars count the things stored in Neo4j: Wikipedia
            articles, topics, and text chunks. They show what the graph
            contains, not how the items are connected.
          </p>
          """
        + node_chart.to_html(
            full_html=False,
            include_plotlyjs=False,
            config={"responsive": True},
        )
        + "</section>"
    )

    readable_relationship_labels = [
        RELATIONSHIP_LABELS.get(name, name)
        for name in relationship_counts
    ]
    relationship_chart = _make_bar_chart(
        title="How are the stored items connected?",
        labels=readable_relationship_labels,
        values=list(relationship_counts.values()),
        x_title="Connections",
        color="#8A54C8",
    )

    chart_sections.append(
        """
        <section class="chart-card">
          <p class="explanation">
            These bars count the links between stored items. For example,
            an article-to-text link connects an article to one of its text
            chunks. These are connections, not additional articles or
            chunks. Article-to-concept links represent the topic
            associations added to this project's graph.
          </p>
          """
        + relationship_chart.to_html(
            full_html=False,
            include_plotlyjs=False,
            config={"responsive": True},
        )
        + "</section>"
    )

    if chunk_lengths:
        chunk_chart = _make_chunk_length_chart(chunk_lengths)

        chart_sections.append(
            """
            <section class="chart-card">
              <p class="explanation">
                This chart groups text chunks by length. The horizontal
                axis shows the number of characters in a chunk; the
                vertical axis shows how many chunks fall within each
                length range. It helps show how the article text was
                divided. It does not measure answer quality.
              </p>
              """
            + chunk_chart.to_html(
                full_html=False,
                include_plotlyjs=False,
                config={"responsive": True},
            )
            + "</section>"
        )

    return f"""
    <section id="ingestion-tab" class="tab-panel active">
      <h2>Ingestion</h2>
      <p class="intro">
        Ingestion downloads Wikipedia text, divides it into chunks, and
        stores the articles and their connections for later question
        answering.
      </p>

      <div class="summary">
        <div class="summary-card">
          <strong>{total_articles:,}</strong>
          <span>Wikipedia articles</span>
        </div>
        <div class="summary-card">
          <strong>{total_topics:,}</strong>
          <span>Topics</span>
        </div>
        <div class="summary-card">
          <strong>{total_chunks:,}</strong>
          <span>Text chunks</span>
        </div>
        <div class="summary-card">
          <strong>{total_relationships:,}</strong>
          <span>Connections</span>
        </div>
      </div>

      {''.join(chart_sections)}
    </section>
    """


def _make_queries_tab() -> str:
    """Build the query-history tab."""
    records = _load_query_history()

    if not records:
        return """
        <section id="queries-tab" class="tab-panel">
          <h2>Questions and Answers</h2>
          <p class="intro">
            Questions and generated answers will appear here after you run
            a query.
          </p>
          <p class="empty-state">
            No questions have been recorded yet.
          </p>
        </section>
        """

    entries = []

    for record in records:
        timestamp = escape(str(record.get("timestamp", "Time unavailable")))
        question = escape(str(record.get("question", "")))
        answer = escape(str(record.get("answer", "")))

        entries.append(
            f"""
            <article class="query-card">
              <p class="query-time">{timestamp}</p>
              <h3>Question</h3>
              <p class="query-question">{question}</p>
              <details>
                <summary>Show answer</summary>
                <div class="query-answer">{answer}</div>
              </details>
            </article>
            """
        )

    return f"""
    <section id="queries-tab" class="tab-panel">
      <h2>Questions and Answers</h2>
      <p class="intro">
        Each entry shows a question asked in the application and the answer
        generated from the retrieved evidence. Newest questions appear first.
      </p>
      {''.join(entries)}
    </section>
    """


